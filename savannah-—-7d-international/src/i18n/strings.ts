export type Strings = (typeof strings)['en'];

export function t(lang: SupportedLang): Strings {
  return strings[lang] as Strings;
}

/** Arabic-Indic digits for display in Arabic. */
export function localizeDigits(s: string, lang: SupportedLang): string {
  if (lang !== 'ar') return s;
  return s.replace(/[0-9]/g, (d) => '٠١٢٣٤٥٦٧٨٩'[Number(d)]);
}
